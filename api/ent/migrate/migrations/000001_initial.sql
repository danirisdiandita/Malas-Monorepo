CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  google_id VARCHAR,
  email VARCHAR NOT NULL,
  name VARCHAR NOT NULL,
  picture VARCHAR,
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE users ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE users ALTER COLUMN google_id DROP NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS users_google_id_key ON users (google_id);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (email);

CREATE TABLE IF NOT EXISTS accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR NOT NULL,
  provider_account_id VARCHAR NOT NULL,
  access_token VARCHAR,
  refresh_token VARCHAR,
  scope VARCHAR,
  user_accounts BIGINT NOT NULL REFERENCES users (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS account_provider_provider_account_id ON accounts (provider, provider_account_id);

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token VARCHAR NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  user_refresh_tokens BIGINT NOT NULL REFERENCES users (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS refresh_tokens_token_key ON refresh_tokens (token);

CREATE TABLE IF NOT EXISTS sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash VARCHAR NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  ip_address VARCHAR,
  user_agent VARCHAR,
  created_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  user_sessions BIGINT NOT NULL REFERENCES users (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS sessions_token_hash_key ON sessions (token_hash);
